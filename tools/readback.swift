// Readback probe: does native CoreBluetooth receive the lamp's status notifications?
//
//   swift tools/readback.swift [lamp-id]          lamp-id: 12 hex digits from lamps.json (default: first lamp seen)
//   swift tools/readback.swift --selftest
//
// Connects, logs in with credentials typed at runtime (never stored or printed), subscribes to
// the status characteristic, sends the AwoX app's status query and schedule reads for slots
// 1-16, and prints every notification decrypted. No writes besides the login and those queries.
import CoreBluetooth
import CommonCrypto
import Foundation

let serviceUUID = CBUUID(string: "00010203-0405-0607-0809-0a0b0c0d1910")
let statusUUID = CBUUID(string: "00010203-0405-0607-0809-0a0b0c0d1911")
let commandUUID = CBUUID(string: "00010203-0405-0607-0809-0a0b0c0d1912")
let pairUUID = CBUUID(string: "00010203-0405-0607-0809-0a0b0c0d1914")

func hex(_ b: [UInt8]) -> String { b.map { String(format: "%02x", $0) }.joined() }
func pad16(_ b: [UInt8]) -> [UInt8] { Array((b + [UInt8](repeating: 0, count: 16)).prefix(16)) }

// AES-128-ECB on one block, with the vendor's byte reversal of key, input and output.
func aes(_ key: [UInt8], _ value: [UInt8], encrypt: Bool) -> [UInt8] {
    let k = Array(pad16(key).reversed()), v = Array(pad16(value).reversed())
    var out = [UInt8](repeating: 0, count: 16 + kCCBlockSizeAES128), moved = 0
    let status = CCCrypt(CCOperation(encrypt ? kCCEncrypt : kCCDecrypt), CCAlgorithm(kCCAlgorithmAES128),
                         CCOptions(kCCOptionECBMode), k, 16, nil, v, 16, &out, out.count, &moved)
    precondition(status == kCCSuccess && moved == 16, "AES failed")
    return Array(out.prefix(16).reversed())
}
func crc8(_ data: [UInt8]) -> UInt8 {
    var crc: UInt8 = 0
    for byte in data { crc ^= byte; for _ in 0..<8 { crc = (crc & 1) != 0 ? (crc >> 1) ^ 0x6C : crc >> 1 } }
    return crc
}
func combine(_ name: [UInt8], _ pass: [UInt8]) -> [UInt8] { zip(pad16(name), pad16(pass)).map { $0 ^ $1 } }
func pairPacket(_ combined: [UInt8], _ random: [UInt8]) -> [UInt8] { [0x0C] + random + Array(aes(random, combined, encrypt: true).prefix(8)) }
func queryPacket(_ key: [UInt8], _ payload: [UInt8]) -> [UInt8] {
    let fields = [UInt8(payload.count)] + payload
    return [0x02] + aes(key, [crc8(fields)] + fields, encrypt: true)
}

func selfTest() -> Bool {
    // Same dummy vectors as the web page (generated by the upstream Python implementation).
    let c = combine(Array("meshname".utf8), Array("meshpass".utf8)), r: [UInt8] = Array(0...7), s: [UInt8] = Array(8...15)
    let key = aes(c, r + s, encrypt: true)
    return hex(pairPacket(c, r)) == "0c00010203040506077f4e2d01cbd9af89" && hex(key) == "03a53246e89ea73e0a5d38ae66d370d6"
        && aes(key, aes(key, Array(0...15), encrypt: true), encrypt: false) == Array(0...15)
}

func describe(type: UInt8, _ b: [UInt8]) -> String {
    let addr = String(format: "0x%04X", Int(b[0]) | Int(b[1]) << 8)
    switch type {
    case 0x35:
        let routine = b[2] & 0x7F, on = b[2] & 0x80 != 0
        if b[3] == 0xFF || (b[2] == 0 && b[3] == 0) { return "schedule slot read from \(addr): empty/unknown \(hex(Array(b[2...12])))" }
        let minute = Int(b[3] >> 2), hour = Int(b[4] & 0x1F), days = b[5] & 0x7F
        let mode = b[7], light = mode & 4 != 0 ? "light unchanged" : mode & 2 != 0 ? "colour \(b[9])/\(b[10])" : "white \(Int(b[9]) | Int(b[10]) << 8) mired"
        return String(format: "slot %2d %@ %02d:%02d days=0x%02x fade=%d %@ brightness=%d %@  [%@]", routine, on ? "ACTIVE  " : "inactive",
                      hour, minute, days, b[6], mode & 1 != 0 ? "ON " : "OFF", b[8], light, hex(Array(b[2...12])))
    case 0x80, 0x82, 0x01: return "status from \(addr): power=\(b[12] & 1 == 1 ? "on" : "off") raw \(hex(b))"
    default: return "type 0x\(String(format: "%02x", type)) from \(addr): \(hex(b))"
    }
}

final class Probe: NSObject, CBCentralManagerDelegate, CBPeripheralDelegate {
    var central: CBCentralManager!
    var lamp: CBPeripheral?
    var chars = [CBUUID: CBCharacteristic]()
    let wanted: String?
    let combined: [UInt8]
    var random = [UInt8](repeating: 0, count: 8), key: [UInt8]? = nil
    var notifications = 0, queries: [[UInt8]] = []

    init(wanted: String?, combined: [UInt8]) {
        self.wanted = wanted; self.combined = combined; super.init()
        central = CBCentralManager(delegate: self, queue: nil)
    }
    func centralManagerDidUpdateState(_ c: CBCentralManager) {
        if c.state == .poweredOn { print("Scanning for the lamp…"); c.scanForPeripherals(withServices: nil) }
        else if c.state == .unauthorized { print("Bluetooth access denied for this terminal app."); exit(1) }
    }
    func centralManager(_ c: CBCentralManager, didDiscover p: CBPeripheral, advertisementData ad: [String: Any], rssi: NSNumber) {
        guard lamp == nil, let m = ad[CBAdvertisementDataManufacturerDataKey] as? Data, m.count >= 8 else { return }
        let b = [UInt8](m)
        guard b[0] == 0x60, b[1] == 0x01 else { return }
        let id = hex(Array(b[2..<8]))
        if let w = wanted, w != id { return }
        print("Found lamp \(id) (RSSI \(rssi)). Connecting…")
        lamp = p; p.delegate = self; c.stopScan(); c.connect(p)
    }
    func centralManager(_ c: CBCentralManager, didConnect p: CBPeripheral) { p.discoverServices([serviceUUID]) }
    func centralManager(_ c: CBCentralManager, didFailToConnect p: CBPeripheral, error: Error?) { print("Connect failed."); exit(1) }
    func centralManager(_ c: CBCentralManager, didDisconnectPeripheral p: CBPeripheral, error: Error?) { finish("disconnected") }
    func peripheral(_ p: CBPeripheral, didDiscoverServices error: Error?) {
        guard let s = p.services?.first(where: { $0.uuid == serviceUUID }) else { print("Mesh service not found."); exit(1) }
        p.discoverCharacteristics([statusUUID, commandUUID, pairUUID], for: s)
    }
    func peripheral(_ p: CBPeripheral, didDiscoverCharacteristicsFor s: CBService, error: Error?) {
        for ch in s.characteristics ?? [] { chars[ch.uuid] = ch }
        guard let status = chars[statusUUID], let pair = chars[pairUUID], chars[commandUUID] != nil else { print("Characteristics missing."); exit(1) }
        print("Subscribing to status notifications (the lamp has no CCCD; an error here is expected)…")
        p.setNotifyValue(true, for: status)
        _ = SecRandomCopyBytes(kSecRandomDefault, 8, &random)
        p.writeValue(Data(pairPacket(combined, random)), for: pair, type: .withResponse)
    }
    func peripheral(_ p: CBPeripheral, didUpdateNotificationStateFor ch: CBCharacteristic, error: Error?) {
        print("Subscription: isNotifying=\(ch.isNotifying)" + (error.map { " error: \($0.localizedDescription)" } ?? ""))
    }
    func peripheral(_ p: CBPeripheral, didWriteValueFor ch: CBCharacteristic, error: Error?) {
        if let e = error { print("Write error: \(e.localizedDescription)"); return }
        if ch.uuid == pairUUID { DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) { p.readValue(for: ch) } }
        else if !queries.isEmpty { sendNext(p) }
    }
    func peripheral(_ p: CBPeripheral, didUpdateValueFor ch: CBCharacteristic, error: Error?) {
        let v = [UInt8](ch.value ?? Data())
        if ch.uuid == pairUUID {
            guard v.first == 0x0D, v.count >= 9 else { print("Login rejected or no reply (type \(v.first.map { String(format: "0x%02x", $0) } ?? "none")). Check the credentials."); exit(1) }
            key = aes(combined, random + Array(v[1...8]), encrypt: true)
            print("Logged in. Sending status query and schedule reads for slots 1-16…")
            queries = [[0x0A, 0xFF, 0xFF]] + (1...16).map { [0x35, 0x00, 0x00, UInt8($0)] }
            sendNext(p)
            DispatchQueue.main.asyncAfter(deadline: .now() + 15) { self.finish("done") }
        } else if ch.uuid == statusUUID, let key = key, v.count >= 17 {
            notifications += 1
            print("  " + describe(type: v[0], aes(key, Array(v[1...16]), encrypt: false)))
        }
    }
    func sendNext(_ p: CBPeripheral) {
        guard let key = key, let cmd = chars[commandUUID], !queries.isEmpty else { return }
        let q = queries.removeFirst()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) { p.writeValue(Data(queryPacket(key, q)), for: cmd, type: .withResponse) }
    }
    func finish(_ why: String) {
        print("\(why): \(notifications) notification(s) received." + (notifications > 0 ? " Native readback works." : " No notifications reached this Mac."))
        if let l = lamp { central.cancelPeripheralConnection(l) }
        exit(0)
    }
}

let args = Array(CommandLine.arguments.dropFirst())
if args.first == "--selftest" { print(selfTest() ? "selftest PASS" : "selftest FAIL"); exit(selfTest() ? 0 : 1) }
guard selfTest() else { print("Crypto self-test failed; not connecting."); exit(1) }
let wanted = args.first.map { $0.lowercased() }
print("Mesh name: ", terminator: ""); let name = Array((readLine() ?? "").utf8)
let pass = Array(String(cString: getpass("Mesh password (hidden): ")).utf8)
guard (1...16).contains(name.count), (1...16).contains(pass.count) else { print("Credentials must be 1-16 bytes."); exit(1) }
let probe = Probe(wanted: wanted, combined: combine(name, pass))
RunLoop.main.run(until: Date().addingTimeInterval(60))
probe.finish("timeout")
